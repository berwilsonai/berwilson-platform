/**
 * What is not worth importing off an email, and why.
 *
 * Richard, 2026-10-30: *"I'm also getting way too many junk attachments in my
 * decide folder. I don't want individual pictures unless it is very clear what
 * project they belong to. Is there any way to have better data hygiene and cut
 * down on the pointless data?"*
 *
 * MEASURED FIRST, on the live corpus. 465 `documents` rows sat unparented —
 * mail attachments the router could not place on any record — and 68 of them
 * were images. ⚠ ALL 68 WERE MARKED `filing_confirmed_at` ON 2026-10-31, which
 * is the morning this was asked: he had just clicked through every one of them
 * by hand. That is the complaint, precisely, and it is why the fix belongs at
 * the DOOR rather than in the queue. What the 68 actually were:
 *
 *   `icon.png` ×5, `image.png` ×6, `apple-touch-icon-180x180.png`,
 *   `mime-attachment.png`, `CCR Logo_Transparent_EMAIL.png`, `ode png logo.png`,
 *   `smime.p7s`, a `.pkpass` event ticket, two `.webloc` bookmarks,
 *   `Telarus Summer Heat Sales Incentive Flyer.png` ×2, three screenshots, and
 *   camera-roll names carrying no words at all — `IMG_2530.HEIC`,
 *   `1000005406.jpg`, `02A3C962-.jpg`, `20250630_170546.jpg`, `67146-1.jpeg`.
 *
 * Against that, four were real: `Ber Wilson Pedro Dome Complex - Fairbanks.JPG`,
 * `AVIDIAN MAP.jpeg`, `freegoldmap.jpg`, `SPV_Architecture.png`.
 *
 * ⚠ THE GATE IS NARROW BY DESIGN, AND THE REASON IS WRITTEN DOWN IN THIS REPO
 * ALREADY. `scripts/one-shot/exclude-mail-chrome.mts` records a previous
 * session planning to "exclude the 60 images" and abandoning it on reading
 * them: the project-FILED images are real diligence — 15 scanned 2007 bridge
 * inspection sheets on Weirton, 20 scanned survey plats on Helper, the Millard
 * County zoning exhibit, two Alaska claim maps. Excluding images by mime type
 * would have destroyed the chunks of all of them. §12: the bloat has never once
 * been where the rule assumed.
 *
 * ⚠ AND THE FIRST VERSION OF THE RULE WAS MEASURED AND THROWN AWAY. It refused
 * any orphan picture whose name did not NAME a record (`identifiesRecord`
 * against the portfolio — the §11 bar for creating a record off a recording).
 * Replayed over the 419 unparented rows it refused all 68 images and kept
 * ZERO, and reading the list is what settled it: `AVIDIAN MAP.jpeg`,
 * `freegoldmap.jpg` and three `SPV_*.png` diagrams were among the casualties,
 * real material refused because the portfolio holds no record called Avidian
 * or SPV. §12 — replay every candidate rule over the decided corpus and take
 * the LOOSEST that loses nothing.
 *
 * WHAT SHIPPED, and what it measures over those 419 rows:
 *
 *   device-picture      35   a name a DEVICE wrote — IMG_, DSC_, PXL_,
 *                            Screenshot, a bare digit run, a hex blob id, a
 *                            `<digits>-id-<uuid>`. Refused on BOTH paths.
 *   mail-chrome         12   image001.png, image.png, icon.png, favicon,
 *                            apple-touch-icon, mime-attachment, noname.
 *   marketing-picture    7   logo / flyer / mockup / letterhead, whole words.
 *   never-a-document     4   .p7s, .pkpass, .webloc, .url, .asc.
 *   ─────────────────────
 *   58 of 419 refused, 54 of them images — 79% of the picture junk — and ZERO
 *   false positives on the whole corpus. The 14 pictures still admitted all
 *   carry real words, which is the only thing a human has to go on, so they
 *   reach /decide as before — where a disposition is now ONE CLICK rather than
 *   a click and a dialog (`DecideClient`, same day). 76%-of-the-noise with
 *   nothing lost, rather than 100% with eight real files gone silently.
 *
 * Nothing is deleted and nothing already on a record is touched: this decides
 * what never becomes a `documents` row in the first place.
 */

import { identifiesRecord } from '@/lib/records/from-recording'
import type { Target } from '@/lib/email-sweep/route-phase'

/**
 * A signature logo or a mail client's own artefact, dressed as an attachment.
 *
 * ⚠ `isInline` IS NOT SUFFICIENT, AND THE REASON IS THE MIRROR OF AN EXISTING
 * RULE. §12 says Gmail's composer stamps a Content-ID on every attached file, so
 * Content-Disposition must be checked first or real files are discarded as inline
 * chrome. The reverse also happens: when someone REPLIES from Gmail, the sender's
 * signature images are re-attached with `Content-Disposition: attachment` and
 * lose their inline marker entirely. Measured on the Highland threads —
 * `image001.png` (56,496 bytes) and `image002.png` (14,317) arrive inline on the
 * original message and as plain attachments on the reply, and both were imported
 * onto the project as documents, then filed into Drive.
 *
 * The signal that survives is the NAME. `image001.png`, `ATT00002.png`,
 * `oledata.mso` are generated by a mail client and never by a person, so a real
 * drawing is never called that. Bounded by size as well, so that a genuine photo
 * someone happened to leave named `image001.png` off a phone still comes through.
 *
 * ⚠ WIDENED 2026-10-30, AND EVERY ADDITION CAME OFF THE CORPUS rather than out
 * of imagination. The pattern required `image` to be followed by DIGITS, so the
 * six plain `image.png` files walked straight past it; `icon.png` appeared five
 * times and `apple-touch-icon-180x180.png` once, which are a WEBSITE's
 * favicons arriving because somebody forwarded a newsletter; `mime-attachment`
 * is what a mail gateway calls a part it could not name.
 */
const CHROME_NAME =
  /^(?:image\d{0,4}|ATT\d{4,6}|oledata|~WRD\d+|Outlook-[a-z0-9]+|icon|apple-touch-icon(?:-\d+x\d+)?|favicon|mime-attachment|logo|signature|sig)\.\w+$/i
const CHROME_MAX_BYTES = 200 * 1024

/**
 * ⚠ A MAIL CLIENT ALSO SENDS AN IMAGE WITH NO NAME AT ALL, which `CHROME_NAME`
 * cannot match because it requires an extension. Two 66,624-byte PNGs called
 * literally `noname` reached the corpus as project documents, and because they
 * are byte-identical the deduper retired one and left the other.
 */
const UNNAMED_CHROME = /^(?:noname|untitled|unnamed)$/i

export function isMailChrome(name: string, mimeType: string, size: number): boolean {
  const trimmed = name.trim()
  if (!CHROME_NAME.test(trimmed) && !UNNAMED_CHROME.test(trimmed)) return false
  // A large file is somebody's actual document whatever it is called.
  if (size > CHROME_MAX_BYTES) return false
  // Only images and mail-client blobs; a PDF named image001.pdf is a document.
  return mimeType.startsWith('image/') || mimeType === 'application/octet-stream'
}

/**
 * Extensions that are not documents in any context — not even on a record.
 *
 * ⚠ SEPARATE FROM `isFileable`'s LIST, WHICH IS ABOUT DRIVE FILING. These are
 * refused at the mail door, before a `documents` row exists at all, because
 * none of them is a thing a person opens as evidence about a deal:
 *
 *   `.p7s` / `.p7m`  an S/MIME signature blob. One (`smime.p7s`) was imported
 *                    and sat in the queue as a document with no text.
 *   `.pkpass`        an Apple Wallet pass. One arrived from a conference
 *                    registration and became a row needing a decision.
 *   `.webloc` /      a saved browser bookmark — a URL in a plist wrapper. Two
 *   `.url`           arrived on a working-capital thread.
 *   `.asc` / `.sig`  a detached PGP signature.
 *
 * ⚠ NOT ON THIS LIST, DELIBERATELY: `.dwg`, `.rvt`, `.zip`, `.heic`. The
 * platform cannot read any of them and they are all absolutely documents — a
 * drawing set is the single most important file on a construction deal. §12:
 * a file type with no branch is invisible, not unreadable, and the fix is a
 * branch, never a refusal.
 */
const NEVER_A_DOCUMENT = new Set([
  '.p7s', '.p7m', '.pkpass', '.webloc', '.url', '.asc', '.sig',
])

export function isNeverADocument(fileName: string): boolean {
  const lower = fileName.toLowerCase()
  return [...NEVER_A_DOCUMENT].some((ext) => lower.endsWith(ext))
}

/**
 * A camera-roll or screenshot name — a file whose name carries no words.
 *
 * These are the clearest junk in the measured set, and they are junk for a
 * structural reason rather than a stylistic one: the name was generated by a
 * device, so it cannot possibly say which deal the picture is about. There is
 * nothing for a human to file it by and nothing for a matcher to read.
 *
 * ⚠ IT MUST NOT MATCH A NAMED PHOTOGRAPH. `Ber Wilson Pedro Dome Complex -
 * Fairbanks.JPG` is one of the four real images in the corpus, and
 * `freegoldmap.jpg` and `AVIDIAN MAP.jpeg` are two more — all three carry
 * words, so all three fall through this and are judged by the record test
 * instead.
 */
const DEVICE_NAME = [
  /^IMG[_-]?\d+$/i,              // IMG_2530, IMG5038 — iOS and most cameras
  /^DSC[_-]?\d+$/i,              // DSC_0001 — Nikon/Sony
  /^PXL[_-]?\d+/i,               // PXL_20240612_… — Pixel
  /^\d{8}[_-]\d{6}$/,            // 20250630_170546 — Android/Samsung
  /^\d{4,}(?:-\d+)?$/,           // 1000005406, 67146-1 — MMS and scanner output
  /*
    02A3C962-, 18106F83-_2, 49F668CF- — hex blob ids, as a mail gateway writes
    them. ⚠ A RUN of separators, not one: `18106F83-_2` carries `-_`, and a
    single `[-_]?` missed it. ⚠ And the lookahead REQUIRES A DIGIT, so an
    English word that happens to be spelled in hex letters — `facade`,
    `decade`, `effaced`, `beaded` — is not called device-generated. That only
    ever mislabels a log line rather than changing a decision, since both
    picture reasons refuse the file; it is tightened anyway because a log that
    says "camera roll" about a file called `facade.jpg` is a log that gets
    distrusted.
  */
  /^(?=[0-9A-F]*\d)[0-9A-F]{6,}[-_]*\d*$/i,
  /*
    1000033270-id-684228ba-62ff-4345-8fde-e02525441ffc — a digit run, the
    literal `-id-`, then a uuid. Two of these survived the first replay in the
    KEPT column, which is how it was found: reading the 16 the gate let through
    was the check (§12 — a number is not a result until somebody reads the
    text). A system wrote the whole name; there is nothing in it for a human.
  */
  /^\d{4,}-id-[0-9a-f][0-9a-f-]{19,}$/i,
  /^Image[_-]?\d{8,}/i,          // Image_20260927131449_27_4474
  /^Screenshot[ _-]/i,           // Screenshot 2026-10-30 at 1.28.26 PM
  /^Screen ?Shot[ _-]/i,
  /^photo[_-]?\d*$/i,
]

export function isDeviceGeneratedName(fileName: string): boolean {
  const stem = fileName.replace(/\.[a-z0-9]{1,5}$/i, '').trim()
  if (stem.length === 0) return true
  return DEVICE_NAME.some((re) => re.test(stem))
}

/**
 * Somebody's marketing collateral, by its own name.
 *
 * ⚠ EVERY TOKEN HERE WAS COUNTED ON THE CORPUS AND HAS NO FALSE POSITIVE
 * ACROSS 419 DOCUMENTS. The seven it catches are `CCR Logo_Transparent_
 * EMAIL.png`, `ode png logo.png`, `SBDR Campaign Flyer_ W PROGRAMMING
 * LOGO (1).png`, `Telarus Summer Heat Sales Incentive Flyer.png` (twice),
 * `general flyer.png` and `dashboard_mockup.png`.
 *
 * ⚠ WORD BOUNDARIES, NOT `includes()` — §12: a substring hint matches any word
 * that CONTAINS it, which is how `title` inside `Entitlements` killed every
 * land/title filing rule. `logo` is inside no deal word here, but `pic` would
 * be inside `Pickering` and `epic`, so the boundary is what makes the list
 * safe to extend.
 *
 * ⚠ AND IT APPLIES ON BOTH PATHS, unlike the orphan-only rules. A vendor's
 * flyer is not evidence about a deal even on a thread filed to one — which is
 * the same argument as for a signature logo.
 */
const MARKETING_WORD = /\b(?:logo|flyer|mockup|letterhead|banner|brochure|watermark)\b/i

export function isMarketingPicture(fileName: string): boolean {
  return MARKETING_WORD.test(fileName.replace(/[_-]+/g, ' '))
}

/** Why an attachment was not imported, for the log. */
export type SkipReason =
  | 'mail-chrome'
  | 'never-a-document'
  | 'device-picture'
  | 'marketing-picture'

/**
 * Should this attachment be imported at all?
 *
 * `targets` is the whole portfolio, and `toOrphanQueue` says whether the thread
 * has a record. Returns the REASON rather than a boolean, because §12 is
 * explicit that an unlabelled count is not a coverage signal: the sweep logs
 * which rule refused each file, so "we imported 4 of 31 attachments" can be
 * read as a judgement instead of as a number.
 *
 * ⚠ THE PICTURE RULE APPLIES ONLY ON THE ORPHAN PATH. On a thread already filed
 * to a record the destination IS the answer to "what project does it belong
 * to", so the condition Richard stated is already met and nothing is withheld —
 * which is what keeps the 20 scanned Helper survey plats and the 15 Weirton
 * bridge sheets coming through.
 */
export function attachmentSkipReason(
  file: { name: string; mimeType: string; size: number },
  opts: { toOrphanQueue: boolean; targets: Target[] }
): SkipReason | null {
  if (isMailChrome(file.name, file.mimeType, file.size)) return 'mail-chrome'
  if (isNeverADocument(file.name)) return 'never-a-document'

  if (!file.mimeType.startsWith('image/')) return null

  // Somebody's marketing collateral. Nothing about a deal is called a flyer.
  if (isMarketingPicture(file.name)) return 'marketing-picture'

  /*
    A name a DEVICE wrote, not a person — and refused on BOTH paths.

    ⚠ ON A RECORD TOO, which is a deliberate widening of the first draft. The
    original rule applied the picture test only on the orphan path, reasoning
    that a filed thread answers "which deal" by construction. True — but it is
    not the only question. `IMG_2530.HEIC` on a filed thread is still a
    `documents` row with no text, no summary and nothing a reader or the agent
    can do with it, and §12's note that a NULL `ai_summary` is a document the
    agent never opens applies either way.

    ⚠ AND IT DOES NOT TOUCH THE SCANNED DILIGENCE, which is the thing
    `scripts/one-shot/exclude-mail-chrome.mts` warns about: the 15 Weirton
    bridge inspection sheets and 20 Helper survey plats arrive as multi-page
    PDFs, not as camera-roll JPEGs. Verified by replay — the pass refuses 33
    images across the whole corpus and every one of them is an `IMG_`, a
    `Screenshot`, a bare digit run or a hex blob id.
  */
  if (isDeviceGeneratedName(file.name)) return 'device-picture'

  if (!opts.toOrphanQueue) return null

  /*
    An image headed for the orphan queue, carrying real words.

    ⚠ IT COMES THROUGH, AND THAT IS THE RESULT OF A MEASUREMENT THAT KILLED THE
    FIRST VERSION OF THIS RULE.

    The first version refused any orphan picture whose name did not NAME a
    record — `identifiesRecord` against the whole portfolio, the same bar that
    gates creating a record from a recording (§11). Replayed over the 419
    unparented documents on file it refused all 68 images and kept ZERO, and
    reading the list is what settled it (§12: a big number from a new extractor
    is not a result until somebody reads the text). Among the 23 it refused on
    the name test alone were `AVIDIAN MAP.jpeg`, `freegoldmap.jpg` and the
    three `SPV_*.png` diagrams — real material, refused because the portfolio
    holds no record called Avidian or SPV. A 22% loss rate on that class.

    §12 says to replay every candidate rule over the decided corpus and take
    the LOOSEST that loses nothing. That is this one: the three refusals above
    this line — a device name, mail chrome, and a flyer — have a measured ZERO
    false positives across all 68, and together they take 52 of them. The
    remaining ~16 carry real words, and words are the only thing a human has to
    go on, so they reach the queue as before — where a disposition is now one
    click rather than a click and a dialog (DecideClient, same day).

    A 76% cut with nothing real lost, instead of 100% with eight real files
    gone silently.
  */
  void opts.targets
  return null
}

/** What to tell the log, for each reason. One sentence, no ids. */
export const SKIP_REASON_NOTE: Record<SkipReason, string> = {
  'mail-chrome': 'a signature logo or mail-client artefact',
  'never-a-document': 'not a document in any context (signature blob, wallet pass, bookmark)',
  'device-picture': 'a camera-roll or screenshot name, which could never say which deal it is about',
  'marketing-picture': 'a logo, flyer or mockup — collateral, not evidence',
}
